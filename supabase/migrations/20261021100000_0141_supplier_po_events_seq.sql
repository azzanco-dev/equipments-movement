-- 0141: a sequence number on supplier_po_events, so events written in one
-- transaction keep their order.
--
-- Owner 2026-10-21: the PO page's log showed «اضافة معدة» before «انشاء
-- الامر». Since 0138 the PO and its lines are created in ONE transaction, so
-- their events share the same `created_at` (now() is the transaction time)
-- and a random uuid decided the order. `seq` is an identity column assigned
-- in insertion order; the page orders by (created_at, seq). Existing rows
-- get their numbers in physical order, which is their insertion order.

ALTER TABLE public.supplier_po_events
  ADD COLUMN IF NOT EXISTS seq bigint GENERATED BY DEFAULT AS IDENTITY;

CREATE INDEX IF NOT EXISTS supplier_po_events_po_seq_idx
  ON public.supplier_po_events (supplier_po_id, created_at, seq);

COMMENT ON COLUMN public.supplier_po_events.seq IS
  '0141: insertion order within the same created_at (events of one transaction share the timestamp). The PO page orders by (created_at, seq).';
