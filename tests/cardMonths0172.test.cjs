// Migration 0172 (owner decisions 2026-11-03, sales phase 2 «كروت التشغيل»):
// the hours of each equipment card per Saudi month — the database layer only.
// Static checks of the migration's source: the two tables (months with its
// updated_at trigger and UNIQUE, the append-only events), the single SELECT
// policy of each (sales.view OR purchasing.view) and no write policy, the
// three SECURITY DEFINER writers with the fixed search_path, the permission
// check and the stable tokens, the one card_month_due definition and the two
// security_invoker views.
const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')

const root = path.join(__dirname, '..')
const read = (...parts) =>
  fs.readFileSync(path.join(root, ...parts), 'utf8').replace(/\r\n/g, '\n')

const MIGRATION = '20261103110000_0172_equipment_card_months.sql'

const migrations = fs
  .readdirSync(path.join(root, 'supabase', 'migrations'))
  .filter((file) => file.endsWith('.sql'))
  .sort()
const norm = (text) =>
  text
    .replace(/--[^\n]*/g, '')
    .replace(/\s+/g, ' ')
    .trim()
const raw = read('supabase', 'migrations', MIGRATION)
const sql = norm(raw)

/** One function of a migration, from its CREATE to the closing `$$;`. */
const fn = (source, head) => {
  const start = source.indexOf(head)
  assert.ok(start >= 0, head)
  return source.slice(start, source.indexOf('$$;', source.indexOf('$$', start) + 2) + 3)
}

/** One statement from its head to the next `;`. */
const stmt = (source, head) => {
  const start = source.indexOf(head)
  assert.ok(start >= 0, head)
  return source.slice(start, source.indexOf(';', start) + 1)
}

const SIGNATURES = {
  record_equipment_card_month: 'record_equipment_card_month(uuid, date, numeric, text)',
  record_equipment_card_months: 'record_equipment_card_months(date, jsonb)',
  delete_equipment_card_month: 'delete_equipment_card_month(uuid, date)',
}

test('0172 is the single 0172 migration, right after 0171', () => {
  const at = migrations.indexOf(MIGRATION)
  assert.ok(at > 0, 'migration 0172 present')
  assert.match(migrations[at - 1], /_0171_/)
  assert.equal(migrations.filter((file) => /_0172_/.test(file)).length, 1)
})

test('equipment_card_months: the card, the first day of the month, the hours, one row per card and month', () => {
  const table = stmt(sql, 'CREATE TABLE public.equipment_card_months (')
  assert.match(
    table,
    /equipment_card_id uuid NOT NULL REFERENCES public\.equipment_cards\(id\) ON DELETE RESTRICT/,
  )
  assert.match(table, /month date NOT NULL/)
  assert.match(table, /CHECK \(month = date_trunc\('month', month::timestamp\)::date\)/)
  assert.match(table, /hours numeric\(8, 2\) NOT NULL/)
  assert.match(table, /CHECK \(hours >= 0 AND hours <= 9999\)/)
  assert.match(table, /CHECK \(note IS NULL OR char_length\(note\) BETWEEN 1 AND 500\)/)
  assert.match(table, /created_by uuid REFERENCES public\.profiles\(id\) ON DELETE SET NULL/)
  assert.match(table, /created_at timestamptz NOT NULL DEFAULT now\(\)/)
  assert.match(table, /updated_at timestamptz NOT NULL DEFAULT now\(\)/)
  assert.match(table, /UNIQUE \(equipment_card_id, month\)/)
  // The list reads by month first.
  assert.match(
    sql,
    /CREATE INDEX equipment_card_months_month_idx ON public\.equipment_card_months \(month, equipment_card_id\);/,
  )
  // The owner's rule for every editable table.
  assert.match(
    sql,
    /CREATE TRIGGER equipment_card_months_updated_at BEFORE UPDATE ON public\.equipment_card_months FOR EACH ROW EXECUTE FUNCTION public\.update_updated_at\(\);/,
  )
})

