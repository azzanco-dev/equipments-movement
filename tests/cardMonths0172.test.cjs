test('card_month_due: ONE immutable definition, month ÷ standard hours, hour × hours, day NULL', () => {
  const heads = [...sql.matchAll(/CREATE OR REPLACE FUNCTION public\.card_month_due\(/g)]
  assert.equal(heads.length, 1)
  const body = fn(sql, 'CREATE OR REPLACE FUNCTION public.card_month_due(')
  assert.match(body, /p_price numeric, p_rate_unit text, p_hours numeric, p_standard_hours integer \) RETURNS numeric LANGUAGE sql IMMUTABLE/)
  assert.match(body, /WHEN p_price IS NULL OR p_hours IS NULL THEN NULL/)
  assert.match(body, /WHEN p_rate_unit = 'hour' THEN round\(p_price \* p_hours, 2\)/)
  assert.match(body, /WHEN p_rate_unit = 'month' AND p_standard_hours > 0 THEN round\(p_price \* p_hours \/ p_standard_hours, 2\)/)
  assert.match(body, /ELSE NULL END/)
  // The invoker runs it inside the views.
  assert.match(sql, /REVOKE ALL ON FUNCTION public\.card_month_due\(numeric, text, numeric, integer\) FROM PUBLIC, anon;/)
  assert.match(sql, /GRANT EXECUTE ON FUNCTION public\.card_month_due\(numeric, text, numeric, integer\) TO authenticated;/)
  // Called twice per view (client and supplier), never re-implemented inline.
  for (const view of ['sales_card_months', 'sales_card_month_slots']) {
    const body = stmt(sql, `CREATE OR REPLACE VIEW public.${view} `)
    assert.equal([...body.matchAll(/public\.card_month_due\(/g)].length, 2, view)
    assert.doesNotMatch(body, /\* m\.hours/, `${view}: no inline computation`)
  }
})

test('the two views: security_invoker over sales_equipment_cards, the dues and the margin, authenticated only', () => {
  for (const view of ['sales_card_months', 'sales_card_month_slots']) {
    const body = stmt(sql, `CREATE OR REPLACE VIEW public.${view} `)
    assert.match(body, /WITH \(security_invoker = true\) AS SELECT/, view)
    assert.match(body, /public\.sales_equipment_cards sc/, view)
    assert.match(body, /\(sc\.equipment_ownership_status = 'alazani'\) AS owned/, view)
    assert.match(body, /COALESCE\(sc\.client_standard_hours, sc\.standard_hours\) AS due_standard_hours/, view)
    assert.match(body, /WHEN sc\.equipment_ownership_status = 'alazani' THEN NULL ELSE public\.card_month_due\( sc\.supplier_price, sc\.supplier_rate_unit, m\.hours,/, view)
    assert.match(body, /CASE WHEN d\.client_due IS NULL THEN NULL ELSE round\(d\.client_due - COALESCE\(d\.supplier_due, 0\), 2\) END AS margin/, view)
    for (const column of [
      'sc.client_line_id',
      'sc.client_po_id',
      'sc.client_po_number',
      'sc.client_price',
      'sc.client_rate_unit',
      'sc.client_standard_hours',
      'sc.supplier_line_id',
      'sc.supplier_po_id',
      'sc.supplier_po_number',
      'sc.supplier_price',
      'sc.supplier_rate_unit',
      'sc.equipment_code',
      'sc.equipment_lessor_name',
      'sc.company_name_ar',
      'sc.project_name_ar',
      'sc.period_from',
      'sc.period_to',
      'sc.is_open',
    ])
      assert.ok(body.includes(`${column},`), `${view}: ${column}`)
    assert.match(sql, new RegExp(`REVOKE ALL ON public\\.${view} FROM PUBLIC, anon;`))
    assert.match(sql, new RegExp(`GRANT SELECT ON public\\.${view} TO authenticated;`))
  }
  // The recorded months join the record.
  const months = stmt(sql, 'CREATE OR REPLACE VIEW public.sales_card_months ')
  assert.match(months, /FROM public\.equipment_card_months m JOIN public\.sales_equipment_cards sc ON sc\.card_id = m\.equipment_card_id/)
  // The slots: every month of the period so far, LEFT JOINed to the record.
  const slots = stmt(sql, 'CREATE OR REPLACE VIEW public.sales_card_month_slots ')
  assert.match(slots, /\(m\.id IS NOT NULL\) AS recorded/)
  assert.match(slots, /m\.id AS month_id/)
  assert.match(
    slots,
    /generate_series\( date_trunc\('month', sc\.period_from::timestamp\), LEAST\( date_trunc\('month', COALESCE\(sc\.period_to, \(now\(\) AT TIME ZONE 'Asia\/Riyadh'\)::date\)::timestamp\), date_trunc\('month', now\(\) AT TIME ZONE 'Asia\/Riyadh'\) \), interval '1 month' \)/,
  )
  assert.match(slots, /LEFT JOIN public\.equipment_card_months m ON m\.equipment_card_id = sc\.card_id AND m\.month = g\.month/)
  assert.match(raw, /computed on read/i)
})

