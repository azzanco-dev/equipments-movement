test('RLS: one SELECT policy per table for sales.view OR purchasing.view, no write policy', () => {
  for (const table of ['equipment_card_months', 'equipment_card_events']) {
    assert.match(sql, new RegExp(`ALTER TABLE public\\.${table} ENABLE ROW LEVEL SECURITY;`))
    const policies = [...sql.matchAll(new RegExp(`CREATE POLICY (\\w+) ON public\\.${table} FOR (\\w+)`, 'g'))]
    assert.equal(policies.length, 1, `${table}: one policy`)
    assert.equal(policies[0][1], `select_${table}`)
    assert.equal(policies[0][2], 'SELECT')
    assert.match(
      sql,
      new RegExp(
        `CREATE POLICY select_${table} ON public\\.${table} FOR SELECT TO authenticated USING \\(\\(SELECT public\\.has_permission\\('sales\\.view'\\)\\) OR \\(SELECT public\\.has_permission\\('purchasing\\.view'\\)\\)\\);`,
      ),
    )
  }
  assert.doesNotMatch(sql, /FOR (INSERT|UPDATE|DELETE|ALL) TO/)
})

test('the three writers: SECURITY DEFINER, fixed search_path, sales.manage first, authenticated only', () => {
  for (const [name, signature] of Object.entries(SIGNATURES)) {
    const body = fn(sql, `CREATE OR REPLACE FUNCTION public.${name}(`)
    assert.match(body, /LANGUAGE plpgsql SECURITY DEFINER SET search_path = public, pg_temp AS \$\$/, name)
    assert.match(body, /BEGIN PERFORM public\.assert_sales_manage\(\);/, `${name}: the permission check first`)
    const escaped = signature.replace(/[()]/g, '\\$&')
    assert.match(sql, new RegExp(`REVOKE ALL ON FUNCTION public\\.${escaped} FROM PUBLIC, anon;`), name)
    assert.match(sql, new RegExp(`GRANT EXECUTE ON FUNCTION public\\.${escaped} TO authenticated;`), name)
  }
  // The 0169 check raises the shared token.
  const assertFn = fn(norm(read('supabase', 'migrations', '20261102120000_0169_client_pos.sql')), 'CREATE OR REPLACE FUNCTION public.assert_sales_manage(')
  assert.match(assertFn, /RAISE EXCEPTION 'sales_manage_required' USING ERRCODE = '42501'/)
  // Return types and defaults.
  assert.match(
    sql,
    /record_equipment_card_month\( p_card_id uuid, p_month date, p_hours numeric, p_note text DEFAULT NULL \) RETURNS uuid/,
  )
  assert.match(sql, /record_equipment_card_months\( p_month date, p_items jsonb \) RETURNS integer/)
  assert.match(sql, /delete_equipment_card_month\( p_card_id uuid, p_month date \) RETURNS void/)
})

test('record_equipment_card_month: the card locked first, the month within the card and not in the future, the upsert and its events', () => {
  const body = fn(sql, 'CREATE OR REPLACE FUNCTION public.record_equipment_card_month(')
  assert.match(body, /IF p_month IS NULL THEN RAISE EXCEPTION 'invalid_month' USING ERRCODE = '22023'/)
  assert.match(body, /v_month := date_trunc\('month', p_month::timestamp\)::date;/)
  // The card row lock comes before any month read or write.
  const lock = body.indexOf('FROM public.equipment_cards c WHERE c.id = p_card_id FOR UPDATE;')
  assert.ok(lock > 0)
  assert.ok(body.indexOf('public.equipment_card_months') > lock)
  assert.match(body, /IF NOT FOUND THEN RAISE EXCEPTION 'invalid_card' USING ERRCODE = '22023'/)
  // Month to month in Saudi time; period_to NULL = open.
  assert.match(body, /v_month_from := date_trunc\('month', v_card_from::timestamp\)::date;/)
  assert.match(
    body,
    /IF v_month < v_month_from OR \(v_month_to IS NOT NULL AND v_month > v_month_to\) THEN RAISE EXCEPTION 'month_outside_card' USING ERRCODE = '55000'/,
  )
  assert.match(
    body,
    /v_current_month := date_trunc\('month', now\(\) AT TIME ZONE 'Asia\/Riyadh'\)::date; IF v_month > v_current_month THEN RAISE EXCEPTION 'month_in_future' USING ERRCODE = '55000'/,
  )
  assert.match(
    body,
    /IF p_hours IS NULL OR p_hours = 'NaN'::numeric OR p_hours < 0 OR p_hours > 9999 THEN RAISE EXCEPTION 'invalid_hours' USING ERRCODE = '22023'/,
  )
  assert.match(body, /v_note := NULLIF\(btrim\(p_note\), ''\); IF char_length\(v_note\) > 500 THEN RAISE EXCEPTION 'invalid_note' USING ERRCODE = '22023'/)
  // Insert → month_recorded; update → month_updated with old_hours; no event when nothing changed.
  assert.match(
    body,
    /INSERT INTO public\.equipment_card_months \(equipment_card_id, month, hours, note, created_by\) VALUES \(p_card_id, v_month, v_hours, v_note, auth\.uid\(\)\) RETURNING id INTO v_id; PERFORM public\.record_equipment_card_event\( p_card_id, 'month_recorded',/,
  )
  assert.match(body, /IF v_old_hours = v_hours AND v_old_note IS NOT DISTINCT FROM v_note THEN RETURN v_id; END IF;/)
  assert.match(body, /UPDATE public\.equipment_card_months SET hours = v_hours, note = v_note WHERE id = v_id;/)
  assert.match(body, /'month_updated', jsonb_build_object\( 'month', v_month, 'hours', v_hours, 'old_hours', v_old_hours, 'note', v_note/)
})

test('record_equipment_card_months: the array shape, every item in order through the single recorder', () => {
  const body = fn(sql, 'CREATE OR REPLACE FUNCTION public.record_equipment_card_months(')
  assert.match(body, /IF p_items IS NULL OR jsonb_typeof\(p_items\) <> 'array' THEN RAISE EXCEPTION 'invalid_items' USING ERRCODE = '22023'/)
  assert.match(body, /FROM jsonb_array_elements\(p_items\) WITH ORDINALITY AS items\(value, ord\) ORDER BY ord/)
  // A missing key is NULL for jsonb_typeof, so the shape test says IS DISTINCT FROM.
  assert.match(body, /jsonb_typeof\(v_item -> 'card_id'\) IS DISTINCT FROM 'string'/)
  assert.match(body, /jsonb_typeof\(v_item -> 'hours'\) IS DISTINCT FROM 'number'/)
  assert.match(body, /COALESCE\(jsonb_typeof\(v_item -> 'note'\), 'null'\) NOT IN \('string', 'null'\)/)
  assert.match(body, /EXCEPTION WHEN invalid_text_representation THEN RAISE EXCEPTION 'invalid_items'/)
  assert.match(
    body,
    /PERFORM public\.record_equipment_card_month\( v_card_id, p_month, \(v_item ->> 'hours'\)::numeric, v_item ->> 'note' \); v_count := v_count \+ 1;/,
  )
  assert.match(body, /RETURN v_count;/)
  // No transaction control: the caller's transaction is the batch.
  assert.doesNotMatch(body, /\b(COMMIT|ROLLBACK|SAVEPOINT)\b/)
})

